// flagBase and settingBase are the entries of flag 0 and setting 0, so
// FlagCount is how many flags the table names.
const (
	flagBase    = 39
	settingBase = 119
	FlagCount   = settingBase - flagBase
)

// FlagName returns the name the assistant sources use for the unit's flag
// id, and whether they name it at all.
func FlagName(id int) (string, bool) {
	return varName(flagBase, id, settingBase)
}

// SettingName returns the name the assistant sources use for the unit's
// setting id, and whether they name it at all.
func SettingName(id int) (string, bool) {
	return varName(settingBase, id, len(varNames))
}

// varName returns entry base+id, as long as it stays below end and the
// original does not skip it.
func varName(base, id, end int) (string, bool) {
	i := base + id
	if id < 0 || i >= end {
		return "", false
	}
	n := varNames[i]
	if strings.Contains(n, "@") {
		return "", false
	}
	return n, true
}
